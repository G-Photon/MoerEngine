"""Generate configuration declarations, defaults, TOML reads and template (Python 3.8+)."""

import argparse
import json
import math
from pathlib import Path
import re
import sys

CPP_TYPES = {"bool": "bool", "uint32": "uint32", "int": "int", "float": "float", "string": "std::string", "float3": "float3"}
IDENTIFIER = re.compile(r"[A-Za-z][A-Za-z_0-9]*\Z")
CPP_KEYWORDS = set(("alignas alignof and asm auto bitand bitor bool break case catch char class const "
                    "consteval constexpr constinit const_cast continue co_await co_return co_yield decltype default "
                    "delete do double dynamic_cast else enum explicit export extern false float for friend goto if "
                    "inline int long mutable namespace new noexcept not nullptr operator or private protected public "
                    "register reinterpret_cast requires return short signed sizeof static static_assert static_cast "
                    "struct switch template this thread_local throw true try typedef typeid typename union unsigned "
                    "using virtual void volatile wchar_t while xor concept char8_t char16_t char32_t compl "
                    "and_eq not_eq or_eq xor_eq").split())
BANNER = "// Generated by tools/config/generate.py; edit tools/config/schema.json.\n"


def identifier(value):
    return isinstance(value, str) and IDENTIFIER.fullmatch(value) and "__" not in value and value not in CPP_KEYWORDS


def validate_value(kind, value, path, enums):
    if kind == "bool":
        valid = type(value) is bool
    elif kind in ("uint32", "int"):
        low, high = (0, 2**32 - 1) if kind == "uint32" else (-2**31, 2**31 - 1)
        valid = type(value) is int and low <= value <= high
    elif kind == "float":
        valid = type(value) in (int, float) and math.isfinite(value) and abs(value) <= 3.402823466e38
    elif kind == "float3":
        valid = isinstance(value, list) and len(value) == 3
        if valid:
            for index, component in enumerate(value):
                validate_value("float", component, f"{path}[{index}]", enums)
    elif kind in enums:
        valid = value in enums[kind]
    else:
        valid = type(value) is str and "\0" not in value
        if valid:
            value.encode("utf-8")
    if not valid:
        raise ValueError(f"{path}: invalid {kind} value {value!r}")


def validate_group(group, path=""):
    children = group.get("fields", []) + group.get("groups", [])
    names = [child["name"] for child in children]
    types = [child["cpp_type"] for child in group.get("groups", [])]
    symbols = names + types
    if any(not identifier(name) for name in symbols) or len(set(symbols)) != len(symbols):
        raise ValueError(f"{path}: invalid or duplicate member/type")
    for child in children:
        key = f"{path}.{child['name']}" if path else child["name"]
        if "type" in child:
            kind = child["type"]
            if kind not in CPP_TYPES or kind == "float3":
                raise ValueError(f"{key}: unsupported global type {kind!r}")
            validate_value(kind, child["default"], key, {})
            if "template" in child:
                validate_value(kind, child["template"], key, {})
        else:
            validate_group(child, key)


def validate_renderers(schema):
    enums = schema["enums"]
    definitions = {item["name"]: item for item in schema["render_types"]}
    if len(definitions) != len(schema["render_types"]):
        raise ValueError("Duplicate renderer configuration type")
    for kind, members in enums.items():
        if not all(identifier(part) for part in kind.split("::")) or not members or len(set(members)) != len(members):
            raise ValueError(f"Invalid enum {kind!r}")
        if not all(identifier(member) for member in members):
            raise ValueError(f"Invalid enum members: {kind}")
    known = set(CPP_TYPES) | set(enums) | set(definitions)
    seen = set()
    for name, item in definitions.items():
        if not identifier(name):
            raise ValueError(f"Invalid configuration type {name!r}")
        fields = item["fields"]
        names = [field["name"] for field in fields]
        if len(set(names)) != len(names) or any(not identifier(n) or n == name for n in names):
            raise ValueError(f"{name}: invalid/duplicate field")
        for field in fields:
            key, kind = f"{name}.{field['name']}", field["type"]
            if kind not in known or (kind in definitions and kind not in seen):
                raise ValueError(f"{key}: unknown, recursive or out-of-order type {kind!r}")
            if "count" in field:
                if type(field["count"]) is not int or field["count"] <= 0 or len(field["default"]) != field["count"]:
                    raise ValueError(f"{key}: invalid fixed array size")
                values = field["default"]
            elif kind in definitions:
                if "default" in field:
                    raise ValueError(f"{key}: defaults belong to the referenced type")
                continue
            else:
                values = [field["default"]]
            for value in values:
                if kind in definitions:
                    members = {f["name"]: f for f in definitions[kind]["fields"]}
                    if not isinstance(value, dict) or not set(value) <= members.keys():
                        raise ValueError(f"{key}: invalid struct array default")
                    for member, override in value.items():
                        validate_value(members[member]["type"], override, key + "." + member, enums)
                else:
                    validate_value(kind, value, key, enums)
        seen.add(name)
    return definitions


def scalar(kind, value, cpp=False, enums=None):
    if kind == "bool":
        return "true" if value else "false"
    if kind == "string":
        if cpp:
            # Fixed-width octal escapes also support non-BMP UTF-8 without C++ surrogate escapes.
            text = "".join(chr(byte) if 32 <= byte < 127 and byte not in (34, 92) else f"\\{byte:03o}"
                           for byte in value.encode("utf-8"))
            return '"' + text + '"'
        return json.dumps(value, ensure_ascii=False)
    if enums and kind in enums and not cpp:
        return json.dumps(value)
    if enums and kind in enums:
        return kind + "::" + value
    if kind == "float3":
        components = ", ".join(scalar("float", component, cpp) for component in value)
        return f"float3({components})" if cpp else f"[{components}]"
    if kind == "float":
        value = repr(float(value))
        return value + "f" if cpp else value
    return str(value) + ("u" if cpp and kind == "uint32" else "")


def fields(group, path=""):
    for field in group.get("fields", []):
        yield (f"{path}.{field['name']}" if path else field["name"], field)
    for child in group.get("groups", []):
        yield from fields(child, f"{path}.{child['name']}" if path else child["name"])


def declaration(group, indent=4):
    lines, pad = [], " " * indent
    for field in group.get("fields", []):
        lines.append(f"{pad}{CPP_TYPES[field['type']]} {field['name']};")
    for child in group.get("groups", []):
        lines += [f"{pad}struct {child['cpp_type']} {{", *declaration(child, indent + 4), f"{pad}}} {child['name']};"]
    return lines


def initializer(group, indent=4):
    lines, pad = [], " " * indent
    for field in group.get("fields", []):
        lines.append(f"{pad}.{field['name']} = {scalar(field['type'], field['default'], cpp=True)},")
    for child in group.get("groups", []):
        lines += [f"{pad}.{child['name']} = {{", *initializer(child, indent + 4), f"{pad}}},"]
    return lines


def renderer_declaration(item, definitions, indent=0):
    pad, name = " " * indent, item["name"]
    lines = [f"{pad}struct RENDER_API {name} {{", f"{pad}    {name}();"]
    for child in definitions.values():
        if child.get("nested") and child["owner"] == name:
            lines.extend(renderer_declaration(child, definitions, indent + 4))
    for field in item["fields"]:
        kind = CPP_TYPES.get(field["type"], field["type"])
        if "count" in field:
            kind = f"StaticArray<{kind}, {field.get('cpp_count', field['count'])}>"
        lines.append(f"{pad}    {kind} {field['name']};")
    if name == "GridConfig":
        lines += [
            "    // Retain the published spelling as the only storage.",
            "    int& GetLightsPerCell() { return light_per_ceil; }",
            "    int GetLightsPerCell() const { return light_per_ceil; }",
            "    void SetLightsPerCell(int value) { light_per_ceil = value; }",
        ]
    return lines + [f"{pad}}};", ""]


def renderer_defaults(item, definitions, enums):
    name = item["name"]
    qualified = item["owner"] + "::" + name if item.get("nested") else name
    lines = [f"{qualified}::{name}()"]
    assignments = []
    for index, field in enumerate(item["fields"]):
        kind, member = field["type"], field["name"]
        if "count" in field and kind in definitions:
            value = "{}"
            members = {f["name"]: f for f in definitions[kind]["fields"]}
            for i, overrides in enumerate(field["default"]):
                for key, override in overrides.items():
                    assignments.append(f"    {member}[{i}].{key} = {scalar(members[key]['type'], override, True, enums)};")
        elif "count" in field:
            value = "{" + ", ".join(scalar(kind, v, True, enums) for v in field["default"]) + "}"
        elif kind in definitions:
            value = "{}"
        else:
            value = "(" + field.get("default_cpp", scalar(kind, field["default"], True, enums)) + ")"
        lines.append(f"    {':' if index == 0 else ','} {member}{value}")
    lines += ["{", *assignments]
    for field in item["fields"]:
        if "count" in field:
            lines.append(f'    static_assert(std::tuple_size_v<decltype({field["name"]})> == {field["count"]});')
    return lines + ["}", ""]


def renderer_leaves(item, definitions, prefix=""):
    for field in item["fields"]:
        if field.get("runtime_only"):
            continue
        path = f"{prefix}.{field['name']}" if prefix else field["name"]
        if field["type"] in definitions:
            if "count" in field:
                for index in range(field["count"]):
                    yield from renderer_leaves(definitions[field["type"]], definitions, f"{path}[{index}]")
            else:
                yield from renderer_leaves(definitions[field["type"]], definitions, path)
        else:
            yield path, field


def template_renderer_fields(item, definitions, enums, overrides=None):
    result, nested = [], []
    for field in item["fields"]:
        if field.get("runtime_only"):
            continue
        name, kind = field["name"], field["type"]
        if kind in definitions:
            nested.append(field)
        else:
            value = (overrides or {}).get(name, field["default"])
            if "count" in field:
                text = "[" + ", ".join(scalar(kind, v, enums=enums) for v in value) + "]"
            else:
                text = scalar(kind, value, enums=enums)
            if kind in enums:
                result.append("# Values: " + ", ".join(enums[kind]))
            result.append(f"# {name} = {text}")
    return result, nested


def template_renderer_tables(item, path, definitions, enums, overrides=None):
    values, nested = template_renderer_fields(item, definitions, enums, overrides)
    lines = [f"[{path}]", *values, ""]
    for field in nested:
        child_path = path + "." + field["name"]
        if "count" in field:
            for override in field["default"]:
                child = template_renderer_tables(definitions[field["type"]], child_path, definitions, enums, override)
                child[0] = f"# [[{child_path}]]"
                lines.extend(child)
        else:
            lines.extend(template_renderer_tables(definitions[field["type"]], child_path, definitions, enums))
    return lines


def template_group(group, path, definitions, enums):
    lines = [f"[{path}]"]
    if group.get("comment"):
        lines.append("# " + group["comment"])
    for field in group.get("fields", []):
        if field.get("comment"):
            lines.append("# " + field["comment"])
        lines.append(f"{field['name']} = {scalar(field['type'], field.get('template', field['default']))}")
    for item in definitions.values():
        if item.get("path") == path:
            renderer_lines = template_renderer_tables(item, path, definitions, enums)
            lines.extend(renderer_lines[1:])
    lines.append("")
    for child in group.get("groups", []):
        lines.extend(template_group(child, path + "." + child["name"], definitions, enums))
    return lines


def generate(schema):
    if schema.get("version") != 1:
        raise ValueError("Unsupported configuration schema version")
    validate_group(schema)
    definitions = validate_renderers(schema)
    enums = schema["enums"]
    header = [BANNER.rstrip(), "#pragma once", "", '#include "API_Macro.h"', '#include "misc/Types.h"',
              "#include <string>", "#include <string_view>", "", "namespace Moer::Config {",
              "struct CORE_API GlobalConfig {", "    GlobalConfig();", "", *declaration(schema), "",
              "    static GlobalConfig LoadConfigFromTomlFile(const std::string_view& toml_path);",
              "};", "} // namespace Moer::Config", ""]
    defaults = [BANNER.rstrip(), "GlobalConfig::GlobalConfig()"]
    for index, child in enumerate(schema["groups"]):
        defaults += [f"    {':' if index == 0 else ','} {child['name']}{{", *initializer(child, 8), "    }"]
    defaults += ["{}", ""]
    reads = [BANNER.rstrip()]
    for path, field in fields(schema):
        fallback = f"loaded_config.{path}"
        # Preserve the original signed-int conversion policy for legacy unsigned fields.
        if field["type"] == "uint32" and not path.startswith("engine.threading."):
            fallback = f"static_cast<int>({fallback})"
        reads += [f'loaded_config.{path} = toml_config.at_path("{path}").value_or({fallback});']
    reads.append("")
    outputs = {
        "source/runtime/core/include/config/generated/GlobalConfig.generated.h": "\n".join(header),
        "source/runtime/core/source/config/generated/GlobalConfigDefaults.inl": "\n".join(defaults),
        "source/runtime/core/source/config/generated/GlobalConfigLoad.inl": "\n".join(reads),
    }
    enum_reads = [BANNER.rstrip()]
    for kind, members in enums.items():
        enum_reads += [f"void Read(const toml::node_view<const toml::node>& node, {kind}& value) {{",
                       "    const auto text = node.value<std::string_view>();", "    if (!text) { return; }"]
        for member in members:
            enum_reads.append(f'    if (*text == "{member}") {{ value = {kind}::{member}; return; }}')
        enum_reads += ["}", ""]
    outputs["source/runtime/render/renderer/generated/RendererConfigEnums.inl"] = "\n".join(enum_reads)
    for root in ("RasterConfig", "RaytracingConfig"):
        declarations, constructor_lines = [BANNER.rstrip()], [BANNER.rstrip()]
        for name, item in definitions.items():
            if name == root or item.get("owner") == root:
                if not item.get("nested"):
                    declarations.extend(renderer_declaration(item, definitions))
                constructor_lines.extend(renderer_defaults(item, definitions, enums))
        folder = "raster" if root == "RasterConfig" else "raytracing"
        base = f"source/runtime/render/renderer/{folder}/generated/{root}"
        outputs[base + ".generated.h"] = "\n".join(declarations)
        outputs[base + "Defaults.inl"] = "\n".join(constructor_lines)
        load = [BANNER.rstrip()]
        for path, field in renderer_leaves(definitions[root], definitions):
            target = "raster" if root == "RasterConfig" else "raytracing"
            load.append(f'Read(toml_config.at_path("{definitions[root]["path"]}.{path}"), {target}.{path});')
        outputs[f"source/runtime/render/renderer/generated/{root}Load.inl"] = "\n".join(load) + "\n"
    template = ["# MoerEngine configuration",
                "# Generated by tools/config/generate.py; edit tools/config/schema.json.",
                "# Renderer enum values use the case-sensitive names listed beside each field.",
                "# Defaults < low_quality_mode preset < explicit renderer fields; enable_shadow=false wins.",
                "# Renderer fields below are commented optional overrides; uncomment only the values you need.", ""]
    for child in schema["groups"]:
        template.extend(template_group(child, child["name"], definitions, enums))
    for table in schema.get("extra_tables", []):
        template += ["# " + table["comment"], "[" + table["path"] + "]"]
        template += ["# " + value for value in table.get("examples", [])]
        for name, value in table.get("values", {}).items():
            template.append(json.dumps(name) + " = " + scalar("bool", value))
        template.append("")
    outputs["template.MoerEngine.toml"] = "\n".join(template)
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schema", type=Path, default=Path(__file__).with_name("schema.json"))
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--check", action="store_true", help="Reject stale generated files without writing them")
    args = parser.parse_args()
    try:
        outputs = generate(json.loads(args.schema.read_text(encoding="utf-8")))
        stale = []
        for relative, content in outputs.items():
            path = args.root / relative
            if path.exists() and path.read_text(encoding="utf-8") == content:
                continue
            stale.append(relative)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                with path.open("w", encoding="utf-8", newline="\n") as stream:
                    stream.write(content)
        if args.check and stale:
            raise ValueError("Stale generated files: " + ", ".join(stale))
        print(f"Configuration generation {'checked' if args.check else 'completed'}: {len(outputs)} outputs, {len(stale)} changed")
        return 0
    except (OSError, KeyError, TypeError, ValueError) as error:
        print(f"Configuration generation failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
